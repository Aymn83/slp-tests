export const dicts: Record<Lang, Dict> = { ar, en };

export async function getDict(): Promise<{ lang: Lang; t: Dict }> {
  const lang = await getLang();
  return { lang, t: dicts[lang] };
}

export function formatDate(lang: Lang, d: Date | null | undefined): string {
  if (!d) return "—";
  return new Intl.DateTimeFormat(lang === "en" ? "en-GB" : "ar-EG-u-nu-latn", {
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(d);
}

export function formatAge(t: Dict, birth: Date | null | undefined, at: Date = new Date()): string {
  if (!birth) return "—";
  let months = (at.getFullYear() - birth.getFullYear()) * 12 + (at.getMonth() - birth.getMonth());
  if (at.getDate() < birth.getDate()) months -= 1;
  if (months < 0) return "—";
  const y = Math.floor(months / 12);
  const m = months % 12;
  if (t === dicts.en) return `${y}${t.years} ${m}${t.months}`;
  const parts = [arCount(y, "سنة", "سنتان", "سنوات", "سنة"), arCount(m, "شهر", "شهران", "أشهر", "شهراً")].filter(Boolean);
  return parts.join(" و") || "0";
}

// صيغ العدد العربية: 1 مفرد، 2 مثنى، 3–10 جمع، 11+ تمييز مفرد
function arCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 0) return "";
  if (n === 1) return one;
  if (n === 2) return two;
  return `${n} ${n <= 10 ? few : many}`;
}
